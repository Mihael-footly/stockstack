/**
 * The seven piece families and their rotation states.
 *
 * Rotations are written out as explicit cell coordinates rather than computed
 * from a matrix at runtime: it is the same data either way, but a table cannot
 * drift and can be read at a glance when a rotation looks wrong.
 *
 * Coordinates are (x, y) offsets from the piece origin, y growing downward.
 */

export type PieceKind = "I" | "J" | "L" | "O" | "S" | "T" | "Z";

export const PIECE_KINDS: readonly PieceKind[] = ["I", "J", "L", "O", "S", "T", "Z"];

export type Cell = readonly [number, number];
export type RotationTable = readonly [readonly Cell[], readonly Cell[], readonly Cell[], readonly Cell[]];

