/**
 * Wall kicks.
 *
 * When a rotation collides, the piece is nudged through this list of offsets
 * and takes the first position that fits. Without kicks a stacker feels rigid
 * and dead — you cannot tuck a piece under an overhang or spin one into a
 * well, which are the two moves that make the game expressive.
 *
 * Keyed by "from>to" rotation state. I has its own table because its centre of
 * rotation sits on a grid line rather than in a cell.
 */
type KickTable = Record<string, readonly Cell[]>;

const KICKS_STANDARD: KickTable = {
  "0>1": [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  "1>0": [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  "1>2": [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  "2>1": [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  "2>3": [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  "3>2": [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  "3>0": [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  "0>3": [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
};

const KICKS_I: KickTable = {
  "0>1": [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  "1>0": [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  "1>2": [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
  "2>1": [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  "2>3": [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  "3>2": [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  "3>0": [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  "0>3": [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
};

const NO_KICK: readonly Cell[] = [[0, 0]];

export function kicksFor(kind: PieceKind, from: number, to: number): readonly Cell[] {
  if (kind === "O") return NO_KICK;
  const table = kind === "I" ? KICKS_I : KICKS_STANDARD;
  return table[`${from}>${to}`] ?? NO_KICK;
}

/** Spawn column offset, chosen so every piece appears centred on a 10-wide field. */
export const SPAWN_X = 3;
